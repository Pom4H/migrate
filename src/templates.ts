export const workflowTemplate = `name: Synchronize migration

on:
  workflow_dispatch:
  schedule:
    - cron: "17 4 * * *"

permissions:
  contents: write
  pull-requests: write

jobs:
  sync:
    runs-on: ubuntu-latest
    timeout-minutes: 30

    steps:
      - uses: actions/checkout@v7.0.1

      - uses: oven-sh/setup-bun@v2.2.0
        with:
          bun-version: 1.4.0

      - name: Install dependencies
        run: bun install

      - name: Synchronize source
        run: bunx @pom4h/migrate sync --check

      - name: Build replacement
        shell: bash
        run: |
          if bun -e 'const p = await Bun.file("package.json").json(); process.exit(p.scripts?.build ? 0 : 1)'; then
            bun run build
          fi

      - name: Open source-diff pull request
        uses: peter-evans/create-pull-request@v8.1.1
        with:
          branch: migrate/source-sync
          delete-branch: true
          commit-message: "chore(content): synchronize legacy source"
          title: "chore(content): synchronize legacy source"
          body: |
            Generated by \`@pom4h/migrate\`.

            Review the semantic source diff and checks before merging.
          labels: content-sync
`;

