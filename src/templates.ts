export function configTemplate(origin: string): string {
  const host = new URL(origin).hostname.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "") || "website";
  return `import { defineMigration, entity, field, website } from "@pom4h/migrate";

export default defineMigration({
  name: ${JSON.stringify(host)},

  source: website(${JSON.stringify(origin)}, {
    discover: ["sitemap", "links"],
    concurrency: 6,
    maxPages: 5_000,
  }),

  entities: [
    entity("page", {
      match: /^(?<path>\\/.*)$/,
      id: ({ url }) => url.pathname === "/" ? "home" : url.pathname.replace(/^\\/|\\/$/g, ""),
      route: ({ url }) => url.pathname,
      fields: {
        title: field.text("h1", { required: false }),
        description: field.attr('meta[name="description"]', "content", { required: false }),
        images: field.list("img[src]", { attribute: "src", absolute: true }),
      },
      assetFields: ["images"],
    }),
  ],

  output: {
    generated: "content/generated",
    resolved: "content/resolved",
    overrides: "content/overrides.ts",
  },

  checks: {
    allowEmpty: false,
    maxRemovedRatio: 0.1,
  },
});
`;
}

